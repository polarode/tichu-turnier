    @Test
    fun `accepts identical team and player names in a different tournament of the same organizer`() {
        val first = createTournament("Spring Classic")
        val second = createTournament("Autumn Cup")

        val firstTeam = createTeamSafe(first, "Team Alpha", "Alice", "Bob")
        val secondTeam = createTeamSafe(second, "Team Alpha", "Alice", "Bob")

        assertEquals("Team Alpha", firstTeam.name)
        assertEquals("Team Alpha", secondTeam.name)
        assertEquals(listOf("Alice", "Bob"), secondTeam.players.map { it.name })
    }

    @Test
    fun `a foreign admin cannot create a team in another admin's tournament`() {
        val tournamentId = createTournament("Alice's tournament", asAdmin = owner)

        val ex = assertFailsWith<NotFoundException> {
            createTeam.create(tournamentId, createTeamRequest(), intruder)
        }
        assertEquals(ErrorCode.NOT_FOUND, ex.code)
    }

    @Test
    fun `creating a team in an unknown tournament fails as not-found`() {
        val ex = assertFailsWith<NotFoundException> {
            createTeam.create(TournamentId("does-not-exist"), createTeamRequest(), owner)
        }
        assertEquals(ErrorCode.NOT_FOUND, ex.code)
    }

    // -------------------------------------------------------------------- list

    @Test
    fun `lists the teams of the caller's tournament`() {
        val tournamentId = createTournament("Spring Classic")
        val alpha = createTeamSafe(tournamentId, "Team Alpha", "Alice", "Bob")
        val beta = createTeamSafe(tournamentId, "Team Beta", "Carol", "Dave")

        val teams = listTeams.list(tournamentId, owner)

        assertEquals(listOf(alpha.id, beta.id), teams.map { it.id })
        assertTrue(teams.all { it.tournamentId == tournamentId })
    }

    @Test
    fun `list of a foreign tournament fails as not-found`() {
