/**
 * Pure unit test: no Spring context. The ports are satisfied with real in-memory
 * repositories and a tiny fake for the id generator, so the use cases are exercised
 * in isolation and deterministically.
 *
 * Covers the full team validation matrix at the use-case seam: field rules, the
 * tournament-scoped uniqueness rules (team name, player name, two identical
 * players in one team), capacity enforcement and the ownership rule inherited from
 * the tournament phase. The cross-tournament acceptance is proven by the same
 * organizer running two tournaments with identical names.
 */
class TeamUseCasesTest {

    private val tournamentRepository = InMemoryTournamentRepository()
    private val teamRepository = InMemoryTeamRepository()
    private val idGenerator = object : IdGenerator {
        private var counter = 0
        override fun newId(): String = "id-${++counter}"
    }

    private val owner = AdminUserId("admin-owner")
    private val intruder = AdminUserId("admin-intruder")

    private val clock = java.time.Clock.fixed(java.time.Instant.parse("2026-01-01T12:00:00Z"), java.time.ZoneOffset.UTC)
    private val createTournament = CreateTournamentCommand(tournamentRepository, idGenerator, clock)
    private val createTeam = CreateTeamCommand(tournamentRepository, teamRepository, idGenerator)
    private val listTeams = ListTeamsQuery(tournamentRepository, teamRepository)
    private val getTeam = GetTeamQuery(tournamentRepository, teamRepository)
    private val updateTeam = UpdateTeamCommand(tournamentRepository, teamRepository)
    private val deleteTeam = DeleteTeamCommand(tournamentRepository, teamRepository)

    private fun createTournament(name: String, asAdmin: AdminUserId = owner, maxTeams: Int = 16) =
        createTournament.create(
            com.example.template.application.api.TournamentWriteRequest(name, "", maxTeams),
            asAdmin,
        ).id

    private fun createTeamRequest(
        name: String = "Team Alpha",
        playerOne: String = "Alice",
        playerTwo: String = "Bob",
    ) = TeamWriteRequest(name, playerOne, playerTwo)

    private fun createTeamSafe(
        tournamentId: TournamentId,
        name: String,
        playerOne: String,
        playerTwo: String,
        asAdmin: AdminUserId = owner,
    ) = createTeam.create(tournamentId, createTeamRequest(name, playerOne, playerTwo), asAdmin)

    // ------------------------------------------------------------------ create

    @Test
    fun `creates a team with generated ids, trimmed names and exactly two players`() {
        val tournamentId = createTournament("Spring Classic")

        val team = createTeam.create(
            tournamentId,
            createTeamRequest("  Team Alpha  ", "  Alice  ", "  Bob  "),
            owner,
        )

        assertEquals(TeamId("id-2"), team.id, "the team id is generated by the id generator")
        assertEquals(tournamentId, team.tournamentId)
        assertEquals("Team Alpha", team.name, "team name is trimmed")
        assertEquals(2, team.players.size, "a team seats exactly two players")
        assertEquals("Alice", team.players[0].name)
        assertEquals("Bob", team.players[1].name)
        assertTrue(team.players.all { it.teamId == team.id }, "both players point back at their team")
        assertTrue(team.players.all { it.tournamentId == tournamentId }, "players are tournament-scoped")
    }

    @Test
    fun `rejects a blank team name anchored to the name field`() {
        val tournamentId = createTournament("Spring Classic")

        val ex = assertFailsWith<InvalidFieldException> {
            createTeam.create(tournamentId, createTeamRequest("   "), owner)
        }
        assertEquals("name", ex.field)
    }

    @Test
    fun `rejects a team name longer than 255 characters anchored to the name field`() {
        val tournamentId = createTournament("Spring Classic")

        val ex = assertFailsWith<InvalidFieldException> {
            createTeam.create(tournamentId, createTeamRequest("x".repeat(256)), owner)
        }
        assertEquals("name", ex.field)
    }

    @Test
    fun `rejects blank player names anchored to the offending player field`() {
        val tournamentId = createTournament("Spring Classic")

        val ex1 = assertFailsWith<InvalidFieldException> {
