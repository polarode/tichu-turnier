    }

    @Test
    fun `rejects two identical players within one team anchored to the second player`() {
        val tournamentId = createTournament("Spring Classic")

        val ex = assertFailsWith<DuplicateTeamPlayersException> {
            createTeam.create(tournamentId, createTeamRequest(playerOne = "Alice", playerTwo = "Alice"), owner)
        }
        assertEquals(ErrorCode.DUPLICATE_TEAM_PLAYERS, ex.code)
        assertEquals("playerTwoName", ex.field)
    }

    @Test
    fun `rejects two identical players within one team case-insensitively`() {
        val tournamentId = createTournament("Spring Classic")

        val ex = assertFailsWith<DuplicateTeamPlayersException> {
            createTeam.create(tournamentId, createTeamRequest(playerOne = "alice", playerTwo = "ALICE"), owner)
        }
        assertEquals(ErrorCode.DUPLICATE_TEAM_PLAYERS, ex.code)
    }

    @Test
    fun `rejects a duplicate team name within the tournament anchored to the name field`() {
        val tournamentId = createTournament("Spring Classic")
        createTeamSafe(tournamentId, "Team Alpha", "Alice", "Bob")

        val ex = assertFailsWith<DuplicateTeamNameException> {
            createTeam.create(tournamentId, createTeamRequest(name = "Team Alpha", playerOne = "Carol", playerTwo = "Dave"), owner)
        }
        assertEquals(ErrorCode.DUPLICATE_TEAM_NAME, ex.code)
        assertEquals("name", ex.field)
    }

    @Test
    fun `rejects a duplicate team name within the tournament case-insensitively`() {
        val tournamentId = createTournament("Spring Classic")
        createTeamSafe(tournamentId, "Team Alpha", "Alice", "Bob")

        val ex = assertFailsWith<DuplicateTeamNameException> {
