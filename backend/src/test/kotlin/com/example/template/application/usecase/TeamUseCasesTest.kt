        val ex2 = assertFailsWith<InvalidFieldException> {
            createTeam.create(tournamentId, createTeamRequest(playerTwo = "   "), owner)
        }
        assertEquals("playerTwoName", ex2.field)
    }

    @Test
    fun `rejects player names longer than 255 characters anchored to the offending player field`() {
